-- ---------------------------------------------------------------------
--  1) รูปหลักฐานของเรื่องที่แจ้ง
--
--  *** ทำไมเก็บเป็นคอลัมน์เดียว ไม่ทำเป็นตารางแยกให้แนบได้หลายรูป ***
--  หัวข้อที่คนแจ้งบ่อยที่สุด เช่น "อาหารสภาพไม่เหมาะแก่การรับประทาน"
--  ใช้รูปเดียวก็พิสูจน์ได้แล้ว การแนบหลายรูปเพิ่มงานทั้งฝั่งอัปโหลด
--  ฝั่งแสดงผล และฝั่งลบทิ้ง โดยที่ผู้ดูแลแทบไม่ได้ข้อมูลเพิ่ม
--  ถ้าวันหนึ่งจำเป็นจริง ค่อยย้ายไปตารางแยกทีหลังได้ ไม่เสียของ
--
--  *** ทำไมยาวถึง 500 ***
--  ตอนพัฒนาในเครื่องเก็บแค่ "ชื่อไฟล์" แต่ตอนขึ้นคลาวด์เก็บ URL เต็มของ
--  Cloudinary ซึ่งยาวกว่ามาก ต้องเผื่อความยาวไว้ให้พอทั้งสองแบบ
-- ---------------------------------------------------------------------
ALTER TABLE reports
  ADD COLUMN image_url VARCHAR(500) DEFAULT NULL AFTER reason;

-- ---------------------------------------------------------------------
--  2) ข้อความโต้ตอบภายในเรื่องที่แจ้ง
--
--  *** ใครอยู่ในห้องสนทนานี้บ้าง : ผู้แจ้ง กับ ผู้ดูแล เท่านั้น ***
--  ผู้ถูกแจ้ง (ร้านหรือลูกค้าที่โดนแจ้ง) ไม่อยู่ในนี้เด็ดขาด
--  เพราะทั้งระบบออกแบบมาให้ผู้ถูกแจ้งไม่รู้ว่าใครเป็นคนแจ้ง
--  ถ้าดึงเขาเข้ามาคุยด้วย ตัวตนคนแจ้งจะหลุดทันทีจากสำนวนหรือรายละเอียด
--  ผู้ถูกแจ้งยังได้รับผลการตรวจสอบผ่าน resolution_message เหมือนเดิม
--
--  *** ทำไมต้องเก็บ sender_role ทั้งที่รู้ได้จาก users.role ***
--  บทบาทของบัญชีเปลี่ยนได้ในอนาคต แต่ประวัติการสนทนาต้องไม่เปลี่ยนตาม
--  ถ้าไป JOIN เอาตอนอ่าน ข้อความเก่าที่ผู้ดูแลเคยพิมพ์อาจกลายเป็น
--  ข้อความของลูกค้าไปเฉย ๆ เพียงเพราะบัญชีนั้นถูกลดสิทธิ์ทีหลัง
--
--  ON DELETE CASCADE ที่ report_id
--    เรื่องถูกลบ = บทสนทนาของเรื่องนั้นไม่มีความหมายอีกต่อไป ลบตามได้เลย
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS report_messages (
  message_id  INT UNSIGNED NOT NULL AUTO_INCREMENT,
  report_id   INT UNSIGNED NOT NULL,
  sender_id   INT UNSIGNED NOT NULL,
  -- บทบาทของคนพิมพ์ ณ ตอนที่พิมพ์ ใช้เลือกฝั่งซ้าย/ขวาของฟองข้อความ
  sender_role ENUM('reporter','admin') NOT NULL,
  message     VARCHAR(1000) NOT NULL,
  created_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (message_id),
  -- อ่านทั้งห้องทีเดียวเรียงตามเวลา จึงทำ index คู่ไว้ให้ตรงกับการใช้งานจริง
  KEY idx_report_messages_report (report_id, created_at),
  CONSTRAINT fk_report_messages_report FOREIGN KEY (report_id)
    REFERENCES reports (report_id) ON DELETE CASCADE,
  CONSTRAINT fk_report_messages_sender FOREIGN KEY (sender_id)
    REFERENCES users (user_id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

