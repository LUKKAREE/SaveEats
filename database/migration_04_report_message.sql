-- ---------------------------------------------------------------------
--  1) ช่องข้อความที่ผู้ดูแลส่งถึงเจ้าของสิ่งที่ถูกแจ้ง
--
--  *** ทำไมต้องแยกจาก admin_note ที่มีอยู่แล้ว ***
--  admin_note คือบันทึกภายใน ผู้ดูแลจดอะไรก็ได้ รวมถึงชื่อคนแจ้ง
--  ถ้าเอาไปแสดงให้ร้านอ่านตรง ๆ จะกลายเป็นการเปิดเผยตัวคนแจ้ง
--  จึงต้องมีอีกช่องที่ "ตั้งใจเขียนให้ร้านอ่าน" โดยเฉพาะ
-- ---------------------------------------------------------------------
ALTER TABLE reports
  ADD COLUMN resolution_message VARCHAR(500) DEFAULT NULL AFTER admin_note;

-- ---------------------------------------------------------------------
--  2) เพิ่มประเภทแจ้งเตือน 'report'
--
--  มีไว้เพื่อให้แอปแยกได้ว่าแจ้งเตือนใบนี้เกี่ยวกับเรื่องร้องเรียน
--  จะได้กดแล้วพาไปหน้า "เรื่องที่ฉันแจ้ง" ไม่ใช่หน้าการจอง
--
--  *** ต้องเขียนค่าเดิมมาให้ครบทุกตัว ***
--  MODIFY COLUMN เป็นการเขียนทับนิยามทั้งอัน ไม่ใช่การเพิ่มต่อท้าย
--  ถ้าลืมค่าไหน ข้อมูลเดิมที่เป็นค่านั้นจะกลายเป็นค่าว่างทันที
-- ---------------------------------------------------------------------
ALTER TABLE notifications
  MODIFY COLUMN type ENUM('reservation','store','review','report','system')
  NOT NULL DEFAULT 'system';

-- =====================================================================
--  เช็คว่าสำเร็จ
--    - ตาราง reports ต้องมีคอลัมน์ resolution_message
--    - ตาราง notifications คอลัมน์ type ต้องมีตัวเลือก report
-- =====================================================================
