-- ---------------------------------------------------------------------
--  เวลาที่ส่งข้อความ "ใกล้หมดเวลารับอาหาร" ให้ลูกค้าไปแล้ว
--
--  *** ทำไมต้องเก็บ ไม่ปล่อยให้เตือนทุกรอบ ***
--  งานเบื้องหลังวิ่งทุก 5 นาที แต่หน้าต่างการเตือนกว้าง 15 นาที
--  คิวใบเดียวจึงเข้าเงื่อนไขได้ประมาณ 3 รอบ ถ้าไม่มีคอลัมน์นี้จำไว้
--  ลูกค้าจะได้ข้อความเดิมซ้ำ ๆ ทุก 5 นาทีจนคิวหมดอายุ กลายเป็นสแปม
--
--  *** ทำไมเก็บเป็น DATETIME ไม่ใช่ TINYINT(1) แค่ว่าเตือนแล้วหรือยัง ***
--  ค่าเวลาตอบได้ทั้งสองคำถาม คือ "เตือนแล้วหรือยัง" (NULL หรือไม่)
--  และ "เตือนตอนไหน" ซึ่งจำเป็นเวลาไล่ปัญหาว่าทำไมลูกค้าบอกไม่ได้รับข้อความ
--  ค่าที่เก็บเพิ่มคือ 5 ไบต์ต่อแถว แลกกับข้อมูลที่ใช้ตรวจสอบได้จริง
--
--  *** ทำไม NULL ได้ ***
--  คิวที่เพิ่งจองยังไม่เคยถูกเตือน ค่าต้องว่างไว้ก่อน
--  แถวเก่าทั้งหมดในฐานข้อมูลจะได้ NULL อัตโนมัติ ซึ่งถูกต้องแล้ว
--  (คิวเก่าที่ยังเปิดอยู่และใกล้หมดเวลา จะถูกเตือน 1 ครั้งในรอบถัดไป)
-- ---------------------------------------------------------------------
ALTER TABLE reservations
  ADD COLUMN reminder_sent_at DATETIME DEFAULT NULL AFTER expires_at;

