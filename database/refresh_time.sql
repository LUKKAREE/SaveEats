-- ---------------------------------------------------------------------
--  1) เลื่อนเวลารับอาหาร และเปิดโพสต์กลับมาขาย
--
--  *** ทำไมต้องรวม expired เข้ามาด้วย ***
--  ไฟล์รุ่นก่อนอัปเดตเฉพาะ active กับ sold_out ซึ่งใช้ได้แค่ตอนที่โพสต์
--  ยังไม่ถูกปิด แต่ถ้าทิ้งข้อมูลไว้ข้ามวัน งานเบื้องหลังจะปิดทุกโพสต์เป็น expired
--  ไปหมดแล้ว คำสั่งเดิมจึงไม่อัปเดตอะไรเลยสักแถว หน้าแรกก็ยังว่างเหมือนเดิม
--
--  *** ทำไมไม่แตะ hidden ***
--  hidden คือโพสต์ที่ร้านตั้งใจซ่อนเอง หรือโพสต์ที่ใช้ทดสอบแล้วเก็บไป
--  การปลุกกลับมาขายเองโดยที่เจ้าของไม่ได้สั่ง ถือว่าทำเกินหน้าที่ของไฟล์นี้
--
--  quantity_left = 0 ให้เป็น sold_out ไม่ใช่ active
--  เพราะโพสต์ที่ไม่มีของเหลือแล้ว ไม่ควรไปโผล่ให้ลูกค้ากดจองแล้วเจอ error
-- ---------------------------------------------------------------------
--  *** ทำไมช่วงเวลากว้างถึง 30 ชั่วโมง แทนที่จะเป็น NOW() ถึง NOW()+6 ชั่วโมง ***
--  NOW() ที่รันผ่าน npm run migrate ได้เวลาเป็น UTC ซึ่งช้ากว่าเวลาที่แอปใช้ 7 ชั่วโมง
--  (ตรวจพบ 10 ก.ย. 2569 : รันตอน 02:00 น. แต่ค่าที่เขียนลงไปเป็น 19:00 ของวันก่อนหน้า)
--  ถ้าตั้ง pickup_end = NOW() + 6 ชั่วโมง จะได้เวลาที่เป็นอดีตไปแล้ว 1 ชั่วโมง
--  งานเบื้องหลังก็จะปิดโพสต์เป็น expired ทันทีที่วิ่งรอบถัดไป รันแล้วเหมือนไม่ได้รัน
--
--  การเปิดช่วงกว้าง -12 ถึง +18 ชั่วโมง ทำให้ใช้ได้ทั้งกรณีที่ NOW() เป็นเวลาไทย
--  และกรณีที่เป็น UTC โดยไม่ต้องไปไล่แก้ time zone ของเซิร์ฟเวอร์ฐานข้อมูล
--  ซึ่งเป็นงานที่ใหญ่กว่าและเสี่ยงกว่าสำหรับไฟล์ที่มีไว้แค่เตรียมข้อมูลทดลอง
UPDATE posts
   SET pickup_start = DATE_SUB(NOW(), INTERVAL 12 HOUR),
       pickup_end   = DATE_ADD(NOW(), INTERVAL 18 HOUR),
       status       = CASE WHEN quantity_left > 0 THEN 'active' ELSE 'sold_out' END
 WHERE status IN ('active', 'sold_out', 'expired');

-- ---------------------------------------------------------------------
--  2) เลื่อนเวลาของการจองที่ยังไม่ปิด จะได้ยังสแกน QR ทดสอบได้
--
--  reminder_sent_at ตั้งกลับเป็น NULL ด้วย (RQ-045)
--  เพราะการเลื่อนเวลาหมดอายุออกไปเท่ากับเริ่มนับใหม่
--  ถ้าไม่ล้าง คิวเดิมจะไม่ถูกเตือนอีกเลย แล้วจะทดสอบการเตือนซ้ำไม่ได้
-- ---------------------------------------------------------------------
UPDATE reservations
   SET pickup_start     = DATE_SUB(NOW(), INTERVAL 12 HOUR),
       pickup_end       = DATE_ADD(NOW(), INTERVAL 18 HOUR),
       expires_at       = DATE_ADD(NOW(), INTERVAL 18 HOUR),
       reminder_sent_at = NULL
 WHERE status IN ('confirmed', 'waiting');

-- ---------------------------------------------------------------------
--  3) ตรวจผลลัพธ์ ต้องเห็นโพสต์สถานะ active อย่างน้อย 1 รายการ
-- ---------------------------------------------------------------------
SELECT post_id, food_id, quantity_left, pickup_start, pickup_end, status
  FROM posts
 ORDER BY post_id;
